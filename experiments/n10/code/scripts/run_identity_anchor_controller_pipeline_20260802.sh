#!/usr/bin/env bash
set -euo pipefail

if [[ "$#" -ne 5 ]]; then
    echo "usage: $0 TASK BASELINE_VARIANT ANCHOR_STEP PHYSICAL_GPU LABEL" >&2
    exit 2
fi

TASK="$1"
BASELINE_VARIANT="$2"
ANCHOR_STEP="$3"
PHYSICAL_GPU="$4"
LABEL="$5"
PIPELINE_AUDIT_LENGTHS="${PIPELINE_AUDIT_LENGTHS:-20 25 30 40 50 60 75 100}"

RUNNER=/data/paperexperiment/LooPlus/scripts/run_paper_length_telomere_remote_20260731.sh

common_environment=(
    BASELINE_VARIANT="${BASELINE_VARIANT}"
    CONTROLLER_CURRICULUM=logical_range
    CONTROLLER_LOGICAL_MAX_LENGTH=40
    CONTROLLER_LABEL_OVERRIDE="${LABEL}"
    CONTROLLER_SEED=211001
    CONTROLLER_TRAINING_PROFILE=identity_long_warmup
    CONTROLLER_INITIALIZATION=identity
    CONTROLLER_ANCHOR_STEP="${ANCHOR_STEP}"
    CONTROLLER_WARMUP_UPDATES=1024
    CONTROLLER_FINAL_LR_RATIO=0.1
    CONTROLLER_DENSE_STAGE_COUNT=0
    CONTROLLER_GRAD_CLIP=0.1
    ALLOW_SHARED_GPU=1
    DECLARED_PEAK_MIB=8192
    RESERVE_MIB=16384
    PAPER_CUDA_MEMORY_FRACTION=0.10
)

env "${common_environment[@]}" \
    "${RUNNER}" controller "${TASK}" adaptive_step "${PHYSICAL_GPU}" 0

env "${common_environment[@]}" \
    AUDIT_BATCH_SIZE=32 \
    AUDIT_BATCHES=16 \
    AUDIT_LENGTHS="${PIPELINE_AUDIT_LENGTHS}" \
    AUDIT_MAXIMUM_STEP=132 \
    AUDIT_MODES="full no_AB identity_D" \
    "${RUNNER}" audit "${TASK}" adaptive_step "${PHYSICAL_GPU}" 0
